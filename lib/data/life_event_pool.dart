import '../domain/player_attributes.dart';

enum CareerPhase { youth, rise, prime, veteran }

enum LifeEventTheme { training, health, club, match, publicLife }

class LifeScenarioSeed {
  const LifeScenarioSeed({
    required this.id,
    required this.phase,
    required this.theme,
    required this.titleZh,
    required this.titleEn,
    required this.contextZh,
    required this.contextEn,
  });

  final String id;
  final CareerPhase phase;
  final LifeEventTheme theme;
  final String titleZh;
  final String titleEn;
  final String contextZh;
  final String contextEn;
}

class LifeActionSeed {
  const LifeActionSeed({
    required this.id,
    required this.titleZh,
    required this.titleEn,
    required this.descriptionZh,
    required this.descriptionEn,
    required this.delta,
    this.trainingLoadDelta = 0,
    this.injuryRiskDelta = 0,
    this.baseWeight = 10,
    this.minimums = const {},
    this.maximums = const {},
    this.causesTransfer = false,
  });

  final String id;
  final String titleZh;
  final String titleEn;
  final String descriptionZh;
  final String descriptionEn;
  final AttributeDelta delta;
  final int trainingLoadDelta;
  final int injuryRiskDelta;
  final double baseWeight;
  final Map<PlayerAttribute, int> minimums;
  final Map<PlayerAttribute, int> maximums;
  final bool causesTransfer;
}

class LifeCandidate {
  const LifeCandidate({required this.scenario, required this.action});

  final LifeScenarioSeed scenario;
  final LifeActionSeed action;

  String get id => '${scenario.id}.${action.id}';
}

/// Planner-owned event content.
///
/// Every phase contains 20 scenario seeds. Each scenario is combined with the
/// five actions belonging to its theme, creating exactly 100 raw candidate
/// options before the character model applies eligibility and weights.
abstract final class LifeEventPool {
  static CareerPhase phaseForAge(int age) {
    if (age <= 18) return CareerPhase.youth;
    if (age <= 23) return CareerPhase.rise;
    if (age <= 30) return CareerPhase.prime;
    return CareerPhase.veteran;
  }

  static List<LifeCandidate> rawOptionsFor(CareerPhase phase) {
    final scenarios = _scenarios.where((item) => item.phase == phase);
    return [
      for (final scenario in scenarios)
        for (final action in _actionsByTheme[scenario.theme]!)
          LifeCandidate(scenario: scenario, action: action),
    ];
  }

